from mjai.utils import gpu_assert

TOOLS_DIR = Path(__file__).resolve().parents[2] / "tools"
if str(TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(TOOLS_DIR))

import gen_nn_golden  # noqa: E402

GOLDEN_PATH = Path(__file__).resolve().parent / "data" / "nn_updates_golden.json"
NUM_ACTIONS = 4
OBS = [0.3, -0.7, 1.0, 0.1]

# Tolerance for the pre-merge fixture.
#
# The fixture is an equivalence guard, and was originally asserted with ``==``.
# That is only reproducible on the machine that recorded it: float32 reductions
# reassociate with whichever BLAS kernel a box picks (AVX2 vs AVX-512, thread
# count, torch build), which moves the last two or three significant digits.
# The guard was therefore machine-locked — it failed on any other host, which
# AGENTS.md §5 classes as a bug to fix rather than tolerate.
#
# Measured on a host other than the fixture's (8 vCPU Cascade Lake, torch
# 2.11.0+cu128, CPU mode) over all 6 scenarios = 1793 recorded values:
#
#   parameters  1636 values, 99.1% still bit-exact, worst 1.7e-07 (1.4 eps)
#   stats        157 values, 66.9% still bit-exact, worst 5.3e-07 (4.4 eps)
#
# float32 eps is 1.19e-07, so the whole spread is a few ULP: arithmetic noise,
# not a numerical difference.
#
# The upper end was calibrated by mutation, not by eye — the structural bugs
# this fixture exists to catch, measured as worst relative deviation:
#
#   entropy term dropped (coef -> 0)     4.0e-03    <- the SMALLEST of them
#   grad clipping enabled (0 -> 1.0)     7.8e-01
#   advantage normalization flipped      1.3e+00
#   theta endpoint swapped (0 <-> 1)     1.9e+00
#
# 1e-5 therefore sits ~19x above the noise ceiling (headroom for hosts noisier
# than this one) and ~400x below the smallest real regression: three orders of
# clearance on each side. ``test_tolerance_still_rejects_a_structural_change``
# pins that lower bound so a future edit cannot quietly loosen it into
# uselessness.
#
# What this does NOT catch is a sub-percent nudge to a hyperparameter knob
# (entropy_coef +-1% moves values by only 1.3e-06). That is not what the
# fixture guards: the knobs are read FROM the fixture, so they cannot drift
# without the fixture drifting with them.
#
# GOLDEN_ABS covers values recorded as exactly 0.0 (e.g. clip_frac on the ACH
# arms), where a relative bound says nothing.
GOLDEN_REL = 1e-5
GOLDEN_ABS = 1e-8


@pytest.fixture(autouse=True)
def _cpu_mode():
    gpu_assert.reset_for_tests()
    gpu_assert.require_cpu()
