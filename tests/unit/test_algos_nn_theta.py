"""The theta interpolation and the shared scaffolding knobs (AGENTS.md §5).

Two responsibilities:

  - **Endpoint equivalence.** ``tests/unit/data/nn_updates_golden.json`` was
    generated by the PRE-merge two-endpoint code (``NNACHUpdate`` /
    ``NNPPOUpdate``, commit 32a25e3) and is never regenerated. Reproducing it
    is what licenses the claim that merging the endpoints into one
    theta-parameterized rule left ACH's numerics — and therefore the paper
    reproduction in docs/reproduce_report.md — untouched.
  - **The interpolation itself**: linearity in theta, endpoint short-circuits,
    knob validation, and the fidelity warnings.

The fixture comparison was originally written as bit-exact ``==``. It is now
compared to a tight tolerance, because bit-exactness is not portable across
machines — see ``GOLDEN_REL`` below for the measurement that set it. The
same-machine bit-exactness claims in this file (the probe-does-not-perturb and
n_epochs tests) still use ``torch.equal`` and are unaffected: both sides of
those comparisons are computed here, so reassociation cancels.
"""

