"""The theta interpolation and the shared scaffolding knobs (AGENTS.md §5).

Two responsibilities:

  - **Numeric reproduction at the endpoints.**
    ``tests/unit/data/nn_updates_golden.json`` was generated by the PRE-merge
    two-endpoint code (``NNACHUpdate`` / ``NNPPOUpdate``, commit 32a25e3) and is
    never regenerated. Reproducing it is what licenses the claim that merging
    the endpoints into one theta-parameterized rule left ACH's numerics — and
    therefore the paper reproduction in docs/reproduce_report.md — untouched
    (AGENTS.md D11).
  - **The interpolation itself**: linearity in theta, endpoint short-circuits,
    knob validation, and the fidelity warnings.

The comparison runs to a tolerance rather than to the bit, because float32
reassociation differs across platforms; the tolerance and its justification
live in ``tools/gen_nn_golden.py``, which owns the comparison so that this file
and ``gen_nn_golden.py --check`` (AGENTS.md §4) cannot drift apart.
"""

from __future__ import annotations

import json
import sys
import warnings
from pathlib import Path

import pytest
import torch

from mjai.agents.mlp import MLPSharedActorCritic
from mjai.algos.nn_updates import NNActorCriticUpdate, safe_log
from mjai.algos.transition import Batch, Transition, make_batch
from mjai.algos.update_rule import ACHFidelityWarning, AlgoConfig
from mjai.utils import gpu_assert

TOOLS_DIR = Path(__file__).resolve().parents[2] / "tools"
if str(TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(TOOLS_DIR))

import gen_nn_golden  # noqa: E402

GOLDEN_PATH = Path(__file__).resolve().parent / "data" / "nn_updates_golden.json"
NUM_ACTIONS = 4
OBS = [0.3, -0.7, 1.0, 0.1]


